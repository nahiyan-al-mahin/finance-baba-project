const listeners = new Set();

export function getLang() {
  return document.documentElement.lang === 'bn' ? 'bn' : 'en';
}

export function t(key, vars = {}) {
  const str = dict[getLang()][key] ?? dict.en[key] ?? key;
  // {cur} is always the user's currency symbol (used in amount labels).
  vars = { cur: currencySymbol(), ...vars };
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
  document.title = root === document && document.body.dataset.titleKey ? `${t(document.body.dataset.titleKey)} · ${t('appName')}` : document.title;
}

export function setLang(lang) {
  document.documentElement.lang = lang === 'bn' ? 'bn' : 'en';
  try {
    localStorage.setItem('fb-lang', document.documentElement.lang);
  } catch {}
  applyI18n();
  listeners.forEach((fn) => fn());
}

export function onLangChange(fn) {
  listeners.add(fn);
}

// ---- Formatting
const locale = () => (getLang() === 'bn' ? 'bn-BD' : 'en-US');
const dateLocale = () => (getLang() === 'bn' ? 'bn-BD' : 'en-GB');
const asDate = (str) => new Date(`${str}T00:00:00Z`);

// ---- Currency (the user's choice; Bangladeshi Taka by default)
let currency = 'BDT';
export const getCurrency = () => currency;
export function setCurrency(code) {
  currency = code || 'BDT';
  applyI18n();
}

export function currencySymbol(code = currency) {
  if (code === 'BDT') return '৳';
  try {
    const part = new Intl.NumberFormat('en-US', { style: 'currency', currency: code, currencyDisplay: 'narrowSymbol' })
      .formatToParts(0)
      .find((p) => p.type === 'currency');
    // A bare letter code (e.g. "SAR") reads better with a space after it.
    return part ? part.value : code;
  } catch {
    return code;
  }
}

export function currencyName(code) {
  try {
    return new Intl.DisplayNames([getLang() === 'bn' ? 'bn' : 'en'], { type: 'currency' }).of(code);
  } catch {
    return code;
  }
}

export const fmt = {
  money(n, code = currency) {
    const digits = code === 'JPY' || code === 'KRW' || code === 'IDR' ? 0 : 2;
    const abs = new Intl.NumberFormat(locale(), { minimumFractionDigits: 0, maximumFractionDigits: digits }).format(Math.abs(n));
    const sym = currencySymbol(code);
    return `${n < 0 ? '−' : ''}${sym}${/^[A-Za-z]{2,}$/.test(sym) ? ' ' : ''}${abs}`;
  },
  number(n) {
    return new Intl.NumberFormat(locale()).format(n);
  },
  pct(n) {
    return `${new Intl.NumberFormat(locale(), { maximumFractionDigits: 1 }).format(Math.abs(n))}%`;
  },
  date(str, opts = { day: 'numeric', month: 'short', year: 'numeric' }) {
    return new Intl.DateTimeFormat(dateLocale(), { ...opts, timeZone: 'UTC' }).format(asDate(str));
  },
  longDate(str) {
    return fmt.date(str, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' });
  },
  monthYear(str) {
    return fmt.date(str, { month: 'long', year: 'numeric' });
  },
  monthShort(ym) {
    return fmt.date(`${ym}-01`, { month: 'short' });
  },
  year(str) {
    return fmt.date(str, { year: 'numeric' });
  },
  time(ms) {
    return new Intl.DateTimeFormat(dateLocale(), { hour: 'numeric', minute: '2-digit' }).format(new Date(ms));
  },
  dateTime(ms) {
    if (!ms) return t('never');
    return new Intl.DateTimeFormat(dateLocale(), { day: 'numeric', month: 'short', year: 'numeric', hour: 'numeric', minute: '2-digit' }).format(new Date(ms));
  },
};

export function categoryLabel(type, id) {
  const cat = (window.FB_CATEGORIES[type] || []).find((c) => c.id === id);
  return cat ? cat[getLang()] : id;
}

export function categoryColor(type, id) {
  const cat = (window.FB_CATEGORIES[type] || []).find((c) => c.id === id);
  return cat ? cat.color : '#868e96';
}

/** A raised, colour-tinted tile holding the category's icon. */
export function categoryTile(type, id, cls = '') {
  return `<span class="cat-tile ${cls}" style="--c:${categoryColor(type, id)}" aria-hidden="true">${icon(`cat-${id}`)}</span>`;
}
